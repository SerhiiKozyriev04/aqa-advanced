// Function Declaration

function calculateArea(width, height) {
    return width * height;
}

console.log(calculateArea(33, 33));

// Function Expression

const calculateAreaExpression = function(width, height) {
    return width * height;
};

console.log(calculateAreaExpression(22, 22));



// Arrow Function

const calculateAreaArrow = (width, height) => {
    return width * height;
};

console.log(calculateAreaArrow(7, 7));



